package com.ascent.climb.data

/**
 * 徒步轨道（TREK）课程正文 —— 简体中文首发。
 *
 * 定位：面向「第一次走长线」的人，偏基础、天气与心态，不涉及冰雪技术。
 * 与高山攀登（climb）的区别不在难度低，而在能力维度不同：
 * 徒步更依赖行程设计、天气判断、负重与耐心，而不是绳索与器械。
 *
 * 命名：t01…t14。多语言化时按 `q.<lesson>#<n>.*` 生成 key，与主轨道一致。
 */

private fun q(
    prompt: String,
    options: List<String>,
    correct: Int,
    explanation: String,
    safety: Boolean = false,
    context: String? = null
) = Question(
    prompt = prompt,
    options = options,
    correct = correct,
    explanation = explanation,
    safetyCritical = safety,
    context = context
)

private fun multi(
    prompt: String,
    options: List<String>,
    correctSet: List<Int>,
    explanation: String,
    safety: Boolean = false
) = Question(
    prompt = prompt,
    options = options,
    correct = -1,
    explanation = explanation,
    safetyCritical = safety,
    type = QType.Multi,
    correctSet = correctSet
)

private fun fill(prompt: String, answers: List<String>, explanation: String) = Question(
    prompt = prompt,
    explanation = explanation,
    type = QType.Fill,
    answers = answers
)

private fun order(prompt: String, options: List<String>, correctOrder: List<Int>, explanation: String) =
    Question(
        prompt = prompt,
        options = options,
        explanation = explanation,
        type = QType.Order,
        correctOrder = correctOrder
    )

