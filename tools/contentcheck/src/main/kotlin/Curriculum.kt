/**
 * 课程大纲 —— 按海拔等级划分单元。
 *
 * 设计意图（四级递进）：
 *   5000 入门  科普为主，徒步型山峰；单元末尾引入技术攀登概念
 *   5000 进阶  技术入门；把技术动作学完一遍
 *   6000       继续科普并强化认知，技术比重上升；高原病专章
 *   7000       大量技术 + 危险判断 + 天气与云图 + 自救
 *   8000       终极考核，检验全部进阶知识
